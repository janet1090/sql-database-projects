-- Vehicle is created before insurance so the VIN foreign key can be created.

CREATE TABLE YHLDRIVERSLICENSE (
    LICENSENO    VARCHAR2(12)  NOT NULL,
    LASTNAME     VARCHAR2(255) NOT NULL,
    FIRSTNAME    VARCHAR2(255) NOT NULL,
    DOB          DATE          NOT NULL,
    ISSUEDATE    DATE          NOT NULL,
    EXPDATE      DATE          NOT NULL,
    GENDER       CHAR(1)       NOT NULL,
    LICENSECLASS VARCHAR2(2)   NOT NULL,
    ADDRESS      VARCHAR2(255) NOT NULL,
    CONSTRAINT DRIVERSLICENSE_PK PRIMARY KEY (LICENSENO),
    CONSTRAINT DRIVERSLICENSE_GENDER_CK CHECK (GENDER IN ('F','M')),
    CONSTRAINT DRIVERSLICENSE_CLASS_CK
        CHECK (LICENSECLASS IN ('G','G1','G2','M','M1','M2','A','B','C','D','E','F')),
    CONSTRAINT DRIVERSLICENSE_DATE_CK CHECK (ISSUEDATE < EXPDATE)
);

CREATE TABLE YHLVEHICLE (
    VIN         VARCHAR2(17) NOT NULL,
    MANUFACTURER VARCHAR2(50) NOT NULL,
    MODEL       VARCHAR2(20) NOT NULL,
    YEAR        NUMBER(4)    NOT NULL,
    PLATE_NO    VARCHAR2(10) NOT NULL,
    COLOR       VARCHAR2(20) NOT NULL,
    FUEL_TYPE   VARCHAR2(10) NOT NULL,
    DOORS       NUMBER(1)    NOT NULL,
    CONSTRAINT VEHICLE_PK PRIMARY KEY (VIN),
    CONSTRAINT VEHICLE_PLATE_UQ UNIQUE (PLATE_NO),
    CONSTRAINT VEHICLE_FUEL_CK CHECK (FUEL_TYPE IN ('Gas','Diesel','Hybrid','Electric')),
    CONSTRAINT VEHICLE_DOORS_CK CHECK (DOORS BETWEEN 2 AND 5),
    CONSTRAINT VEHICLE_COLOR_CK CHECK (COLOR IN ('Black','White','Red','Blue','Silver','Gray'))
);

CREATE TABLE YHLAUTOINSURANCE (
    POLICYNO          VARCHAR2(20) NOT NULL,
    LICENSENO         VARCHAR2(12) NOT NULL,
    VIN               VARCHAR2(17) NOT NULL,
    ANNUALPREMIUM     NUMBER(7,2)  NOT NULL,
    PAYMENT           CHAR(10)     NOT NULL,
    PAYMENTINSTITUTION VARCHAR2(50),
    POLICY_START_DATE DATE,
    POLICY_END_DATE   DATE,
    POLICY_OWNER_NAME VARCHAR2(255),
    CONSTRAINT AUTOINSURANCE_PK PRIMARY KEY (POLICYNO),
    CONSTRAINT AUTOINSURANCE_LICENSE_FK FOREIGN KEY (LICENSENO)
        REFERENCES YHLDRIVERSLICENSE (LICENSENO),
    CONSTRAINT AUTOINSURANCE_VIN_FK FOREIGN KEY (VIN)
        REFERENCES YHLVEHICLE (VIN),
    CONSTRAINT AUTOINSURANCE_PAYMENT_CK CHECK (PAYMENT IN ('Monthly','Annually')),
    CONSTRAINT AUTOINSURANCE_PREMIUM_CK CHECK (ANNUALPREMIUM >= 0),
    CONSTRAINT AUTOINSURANCE_POLICY_DATES_CK
        CHECK (POLICY_END_DATE IS NULL OR POLICY_START_DATE IS NULL OR POLICY_END_DATE >= POLICY_START_DATE)
);

