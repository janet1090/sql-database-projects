-- Hotel Guest and Room Reservation Database
-- Companion implementation based on the COMP122 assignment document.
-- Sample records below are fictional and intended for learning only.
-- Oracle SQL | Run in a clean schema.

CREATE TABLE YHLIGUEST (
    GUEST_ID        NUMBER(8)      NOT NULL,
    FIRSTNAME       VARCHAR2(50)   NOT NULL,
    LASTNAME        VARCHAR2(50)   NOT NULL,
    CONTACT_NO      VARCHAR2(20)   NOT NULL,
    EMAIL           VARCHAR2(100)  NOT NULL,
    ADDRESS         VARCHAR2(100)  NOT NULL,
    LOYALTY_PROGRAM VARCHAR2(8)    NOT NULL,
    CONSTRAINT GUEST_GUEST_ID_PK PRIMARY KEY (GUEST_ID),
    CONSTRAINT GUEST_LOYALTYPROGRAM_CK
        CHECK (LOYALTY_PROGRAM IN ('LEVEL_0','LEVEL_1','LEVEL_2','LEVEL_3'))
);

CREATE TABLE YHLROOMRESERVATION (
    RESERVATIONID   VARCHAR2(10)  NOT NULL,
    GUEST_ID        NUMBER(8)     NOT NULL,
    ROOMTYPE        VARCHAR2(20)  NOT NULL,
    CHECKINDATE     DATE          NOT NULL,
    CHECKOUTDATE    DATE          NOT NULL,
    NUMOFGUESTS     NUMBER(1)     NOT NULL,
    SPECIALREQUESTS VARCHAR2(250),
    STATUS          VARCHAR2(15)  NOT NULL,
    CONSTRAINT ROOMRESERVATION_PK PRIMARY KEY (RESERVATIONID),
    CONSTRAINT ROOMRESERVATION_GUEST_ID_FK FOREIGN KEY (GUEST_ID)
        REFERENCES YHLIGUEST (GUEST_ID),
    CONSTRAINT ROOMRESERVATION_ROOMTYPE_CK
        CHECK (ROOMTYPE IN ('Queen','King','Twin','Hollywood Twin','Double-Double','Studio')),
    CONSTRAINT ROOMRESERVATION_DATE_CK CHECK (CHECKOUTDATE >= CHECKINDATE),
    CONSTRAINT ROOMRESERVATION_STATUS_CK CHECK (STATUS IN ('Confirmed','Cancelled')),
    CONSTRAINT ROOMRESERVATION_GUESTCOUNT_CK CHECK (NUMOFGUESTS BETWEEN 1 AND 9)
);

